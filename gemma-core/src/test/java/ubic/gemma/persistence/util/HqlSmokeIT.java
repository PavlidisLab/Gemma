package ubic.gemma.persistence.util;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import org.hibernate.Session;
import org.junit.jupiter.api.DynamicTest;
import org.junit.jupiter.api.Tag;
import org.junit.jupiter.api.TestFactory;
import org.springframework.test.context.ContextConfiguration;
import ubic.gemma.core.util.test.BaseDatabaseTest5;

import java.io.InputStream;
import java.util.ArrayList;
import java.util.List;
import java.util.stream.Stream;

import static org.junit.jupiter.api.Assertions.assertDoesNotThrow;
import static org.junit.jupiter.api.Assertions.assertNotNull;

/**
 * Mass parse-only smoke test for every statically-extractable HQL string in
 * {@code gemma-core/src/main/java}. Closes the HQL coverage gap from
 * {@code handoffs/HQL_COVERAGE_AUDIT_2026_05_25.md} — 166 directly-uncovered
 * methods + 57 ambiguous-by-name. The test treats every extracted query
 * uniformly, so already-covered queries get a redundant safety net + the
 * uncovered ones get their first test reference.
 *
 * <h2>What this test catches</h2>
 *
 * <ul>
 *   <li>HQL syntax regressions (missing space, mistyped keyword).</li>
 *   <li>Unknown entity / property references — caught at SQM-translation
 *       time, NOT at runtime. A rename in {@code gemma-model} that misses an
 *       HQL string will surface here.</li>
 *   <li>HB6 SQM-translator regressions on novel shapes (sibling test
 *       {@code HibernateSqmFragileShapesIT} pins the known-fragile shapes;
 *       this test catches the long tail).</li>
 * </ul>
 *
 * <h2>What this test does NOT catch</h2>
 *
 * <ul>
 *   <li>Behavioural / data-shape bugs (no rows fetched; no asserts on results).</li>
 *   <li>Query performance — flagged as a follow-up only when something is
 *       OBVIOUSLY pathological; the bar is "this query won't even parse,"
 *       not "this query is slow."</li>
 *   <li>Dynamic HQL built via {@code StringBuilder} or runtime interpolation
 *       — 216 callsites are skipped by the extractor for that reason. Those
 *       need targeted DAO tests; not in scope here.</li>
 * </ul>
 *
 * <h2>Manifest</h2>
 *
 * The HQL strings come from
 * {@code src/test/resources/hql-smoke/hql-manifest.json}, regenerated by
 * {@code src/test/resources/hql-smoke/extract_hql.py} when HQL changes.
 * Re-run the extractor + commit the regenerated manifest as part of any PR
 * that modifies HQL.
 *
 * <h2>Tag</h2>
 *
 * {@code @Tag("integration")} — runs in failsafe, skipped from surefire.
 * The Spring + Hibernate context boot is the only meaningful cost; per-query
 * SQM parse + emit on an empty H2 schema is sub-millisecond.
 */
@Tag("integration")
@ContextConfiguration
public class HqlSmokeIT extends BaseDatabaseTest5 {

    private static final String MANIFEST_RESOURCE = "/hql-smoke/hql-manifest.json";

    @TestFactory
    Stream<DynamicTest> hqlSmokeFromManifest() throws Exception {
        List<HqlEntry> entries = loadManifest();
        assertNotNull( entries, "manifest must be present on the test classpath" );
        return entries.stream().map( e -> DynamicTest.dynamicTest(
                e.label(),
                () -> assertDoesNotThrow( () -> {
                    Session session = sessionFactory.getCurrentSession();
                    // createQuery itself triggers SQM parse. Calling .getQueryString()
                    // forces the SqmQuerySpec build. .list() would also emit + execute
                    // SQL; skipped here because (a) without typed param values it can
                    // throw on type-mismatch unrelated to HQL correctness, and (b)
                    // parse + emit catches every syntactic + metamodel regression we
                    // want.
                    org.hibernate.query.Query<?> q = session.createQuery( e.hql() );
                    assertNotNull( q.getQueryString() );
                } )
        ) );
    }

    // -----------------------------------------------------------------------
    // manifest loader
    // -----------------------------------------------------------------------

    private static List<HqlEntry> loadManifest() throws Exception {
        try ( InputStream in = HqlSmokeIT.class.getResourceAsStream( MANIFEST_RESOURCE ) ) {
            if ( in == null ) {
                throw new IllegalStateException(
                        "HQL manifest not on classpath at " + MANIFEST_RESOURCE
                                + " — regenerate via gemma-core/src/test/resources/hql-smoke/extract_hql.py" );
            }
            ObjectMapper m = new ObjectMapper();
            JsonNode root = m.readTree( in );
            List<HqlEntry> out = new ArrayList<>();
            for ( JsonNode q : root.get( "queries" ) ) {
                String file = q.get( "file" ).asText();
                int line = q.get( "line" ).asInt();
                String hql = q.get( "hql" ).asText();
                out.add( new HqlEntry( file + ":" + line, hql ) );
            }
            return out;
        }
    }

    private record HqlEntry(String label, String hql) {
    }

    @org.springframework.context.annotation.Configuration
    @ubic.gemma.core.context.TestComponent
    static class Config extends BaseDatabaseTestContextConfiguration {
    }
}
