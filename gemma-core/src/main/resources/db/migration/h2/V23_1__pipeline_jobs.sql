-- H2 mirror of mysql/V18__pipeline_jobs.sql — creates the base pipeline schema
-- (PIPELINE_JOB_BATCH / PIPELINE_JOB / PIPELINE_JOB_EVENT). The MySQL stream created
-- these in V18; the H2 stream never got a sister migration, so V24 (attempt/retry
-- columns) and V25 (batch throttle) altered a table that did not exist here. This fills
-- that gap. Version 23.1 slots it ahead of V24, the first migration to touch the table.
--
-- Type choices follow the V5__ticket_layer.sql idioms: BIGINT identity PK, DATETIME(3)
-- for timestamps, and CLOB for the LONGTEXT/TEXT JSON-ish columns (H2's JSON support
-- varies across versions and Hibernate maps these as MaterializedClobType anyway).

CREATE TABLE PIPELINE_JOB_BATCH (
    ID                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    AUDIT_TRAIL_FK    BIGINT       NOT NULL UNIQUE,               -- UK_PIPELINE_JOB_BATCH_AUDIT_TRAIL
    NAME              VARCHAR(255) NOT NULL,
    DESCRIPTION       TEXT         NULL,
    PIPELINE          VARCHAR(64)  NOT NULL,
    SUBMITTED_BY_FK   BIGINT       NOT NULL,
    SUBMITTED_AT      DATETIME(3)  NOT NULL,
    PARAMS_JSON       CLOB         NULL,
    STATE             VARCHAR(16)  NOT NULL DEFAULT 'OPEN',
    KILL_REQUESTED_AT DATETIME(3)  NULL,
    CLOSED_AT         DATETIME(3)  NULL,
    CONSTRAINT CK_PIPELINE_JOB_BATCH_STATE
        CHECK (STATE IN ('OPEN', 'CLOSED', 'CANCELLED'))
);
ALTER TABLE PIPELINE_JOB_BATCH ADD CONSTRAINT FK_PIPELINE_JOB_BATCH_AUDIT_TRAIL
    FOREIGN KEY (AUDIT_TRAIL_FK) REFERENCES AUDIT_TRAIL (ID);
ALTER TABLE PIPELINE_JOB_BATCH ADD CONSTRAINT FK_PIPELINE_JOB_BATCH_SUBMITTED_BY
    FOREIGN KEY (SUBMITTED_BY_FK) REFERENCES CONTACT (ID);
CREATE INDEX IDX_PIPELINE_JOB_BATCH_SUBMITTED_BY  ON PIPELINE_JOB_BATCH (SUBMITTED_BY_FK);
CREATE INDEX IDX_PIPELINE_JOB_BATCH_PIPELINE_STATE ON PIPELINE_JOB_BATCH (PIPELINE, STATE);

CREATE TABLE PIPELINE_JOB (
    ID                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BATCH_FK            BIGINT       NOT NULL,
    EXPERIMENT_FK       BIGINT       NOT NULL,
    STATE               VARCHAR(16)  NOT NULL DEFAULT 'PENDING',
    SCHEDULER_KIND      VARCHAR(16)  NULL,
    SCHEDULER_HANDLE    VARCHAR(255) NULL,
    SUBMITTED_AT        DATETIME(3)  NULL,
    STARTED_AT          DATETIME(3)  NULL,
    FINISHED_AT         DATETIME(3)  NULL,
    LAST_EVENT_AT       DATETIME(3)  NULL,
    LAST_EVENT_KIND     VARCHAR(32)  NULL,
    LAST_PROGRESS_JSON  TEXT         NULL,
    ERROR_MESSAGE       TEXT         NULL,
    CONSTRAINT CK_PIPELINE_JOB_STATE
        CHECK (STATE IN ('PENDING', 'QUEUED', 'RUNNING', 'DONE', 'FAILED', 'CANCELLING', 'CANCELLED')),
    CONSTRAINT CK_PIPELINE_JOB_SCHEDULER_KIND
        CHECK (SCHEDULER_KIND IS NULL OR SCHEDULER_KIND IN ('luigi', 'nextflow', 'mock'))
);
ALTER TABLE PIPELINE_JOB ADD CONSTRAINT UK_PIPELINE_JOB_SCHEDULER_HANDLE
    UNIQUE (SCHEDULER_KIND, SCHEDULER_HANDLE);
ALTER TABLE PIPELINE_JOB ADD CONSTRAINT FK_PIPELINE_JOB_BATCH
    FOREIGN KEY (BATCH_FK) REFERENCES PIPELINE_JOB_BATCH (ID) ON DELETE CASCADE;
ALTER TABLE PIPELINE_JOB ADD CONSTRAINT FK_PIPELINE_JOB_EXPERIMENT
    FOREIGN KEY (EXPERIMENT_FK) REFERENCES INVESTIGATION (ID) ON DELETE CASCADE;
CREATE INDEX IDX_PIPELINE_JOB_BATCH      ON PIPELINE_JOB (BATCH_FK);
CREATE INDEX IDX_PIPELINE_JOB_EXPERIMENT ON PIPELINE_JOB (EXPERIMENT_FK);
CREATE INDEX IDX_PIPELINE_JOB_STATE      ON PIPELINE_JOB (STATE);
CREATE INDEX IDX_PIPELINE_JOB_LAST_EVENT ON PIPELINE_JOB (LAST_EVENT_AT);
CREATE INDEX IDX_PIPELINE_JOB_RECONCILE  ON PIPELINE_JOB (STATE, LAST_EVENT_AT);

CREATE TABLE PIPELINE_JOB_EVENT (
    ID            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    JOB_FK        BIGINT      NOT NULL,
    OCCURRED_AT   DATETIME(3) NOT NULL,
    KIND          VARCHAR(32) NOT NULL,
    PAYLOAD_JSON  TEXT        NULL
);
ALTER TABLE PIPELINE_JOB_EVENT ADD CONSTRAINT FK_PIPELINE_JOB_EVENT_JOB
    FOREIGN KEY (JOB_FK) REFERENCES PIPELINE_JOB (ID) ON DELETE CASCADE;
CREATE INDEX IDX_PIPELINE_JOB_EVENT_JOB_AT ON PIPELINE_JOB_EVENT (JOB_FK, OCCURRED_AT);
