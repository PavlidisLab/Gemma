-- Finish the Symbol-font repair V53 started: every position, not only the fifteen that a scan saw.
--
-- V53 enumerated the fifteen codepoints uib's corpus scan reported, so it inherited that scan's
-- completeness. It was not complete. After V53 ran on production, three datasets still held
-- private-use characters:
--
--   GSE145840 (23504)  "~60-120<U+F06D>g/m3"          -- Symbol 0x6D, mu
--   GSE242163 (91554)  "3<U+F06D>g/kg Vasculotide"    -- four occurrences
--   GSE272571 (57788)  "IFN-gamma<U+F02C> and metallo"-- Symbol 0x2C, comma
--
-- Not a different defect and not unusual Unicode from the submitter: the same Word-paste, at two
-- positions the scan happened not to report. Ruled out as explanations: ACL (all three are
-- anonymously readable), recency (all three predate the scan), and description truncation (there is
-- none in the VO chain, and one sits at character 190 of 625). The scan reported 23,545 datasets
-- against 23,549 in the database.
--
-- So this file does not enumerate observed codepoints. It covers all 185 Symbol positions that have
-- a non-private-use target, taken from the same generated table as SymbolFontPua, and is therefore
-- correct whether or not anybody scanned anything. Idempotent, like V53: a position that is already
-- clean matches nothing.
--
-- The 15 V53 already handled are included again rather than skipped -- re-running them costs one
-- no-op statement each and removes the need for a reader to cross-reference two files to know what
-- is covered.
-- H2 twin; a Flyway-built H2 holds no imported rows, so this is a no-op there.

