-- H2 mirror of mysql/V3__ticket_layer.sql. H2's JSON support varies across
-- versions and Hibernate maps PAYLOAD as MaterializedClobType anyway, so
-- we use CLOB (matches the AUDIT_EVENT.PAYLOAD H2 mapping).

CREATE TABLE TICKET (
    ID                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    AUDIT_TRAIL_FK              BIGINT NOT NULL UNIQUE,
    NAME                        VARCHAR(255) NOT NULL,
    DESCRIPTION                 TEXT NULL,
    TYPE                        VARCHAR(64) NOT NULL,
    STATE                       VARCHAR(32) NOT NULL,
    PRIORITY                    VARCHAR(16) NOT NULL,
    DUE_DATE                    DATETIME(3) NULL,
    REPORTER_FK                 BIGINT NOT NULL,
    ASSIGNEE_FK                 BIGINT NULL,
    CREATED_AT                  DATETIME(3) NOT NULL,
    UPDATED_AT                  DATETIME(3) NOT NULL,
    EXTERNAL_ISSUE_URL          VARCHAR(512) NULL,
    EXTERNAL_ISSUE_SYNC_STATE   VARCHAR(16) DEFAULT 'NONE' NOT NULL
);

ALTER TABLE TICKET ADD CONSTRAINT TICKET_AUDIT_TRAIL_FKC FOREIGN KEY (AUDIT_TRAIL_FK) REFERENCES AUDIT_TRAIL (ID);
ALTER TABLE TICKET ADD CONSTRAINT TICKET_REPORTER_FKC    FOREIGN KEY (REPORTER_FK)    REFERENCES CONTACT (ID);
ALTER TABLE TICKET ADD CONSTRAINT TICKET_ASSIGNEE_FKC    FOREIGN KEY (ASSIGNEE_FK)    REFERENCES CONTACT (ID);

CREATE INDEX TICKET_NAME  ON TICKET (NAME);
CREATE INDEX TICKET_TYPE  ON TICKET (TYPE);
CREATE INDEX TICKET_STATE ON TICKET (STATE);

CREATE TABLE TICKET_TARGET (
    ID           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TICKET_FK    BIGINT NOT NULL,
    TARGET_TYPE  VARCHAR(32) NOT NULL,
    TARGET_ID    BIGINT NOT NULL
);
ALTER TABLE TICKET_TARGET ADD CONSTRAINT TICKET_TARGET_TICKET_FKC FOREIGN KEY (TICKET_FK) REFERENCES TICKET (ID);
ALTER TABLE TICKET_TARGET ADD CONSTRAINT TICKET_TARGET_UNIQUE     UNIQUE (TICKET_FK, TARGET_TYPE, TARGET_ID);
CREATE INDEX TICKET_TARGET_LOOKUP ON TICKET_TARGET (TARGET_TYPE, TARGET_ID);

CREATE TABLE TICKET_EVENT (
    ID           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TICKET_FK    BIGINT NOT NULL,
    ACTOR_FK     BIGINT NOT NULL,
    OCCURRED_AT  DATETIME(3) NOT NULL,
    TYPE         VARCHAR(64) NOT NULL,
    PAYLOAD      CLOB NULL
);
ALTER TABLE TICKET_EVENT ADD CONSTRAINT TICKET_EVENT_TICKET_FKC FOREIGN KEY (TICKET_FK) REFERENCES TICKET (ID);
ALTER TABLE TICKET_EVENT ADD CONSTRAINT TICKET_EVENT_ACTOR_FKC  FOREIGN KEY (ACTOR_FK)  REFERENCES CONTACT (ID);
CREATE INDEX TICKET_EVENT_OCCURRED_AT ON TICKET_EVENT (OCCURRED_AT);
