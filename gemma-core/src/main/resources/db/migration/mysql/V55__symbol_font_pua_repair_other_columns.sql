--
-- V53/V54 repaired INVESTIGATION.NAME and .DESCRIPTION because those are the two fields the original
-- REST scan could see. A sweep of all 325 text columns on production found the defect in five more:
--
--   TREATMENT.DESCRIPTION            2498   <- repaired here
--   INVESTIGATION.SOURCE_METADATA     328   <- deliberately NOT repaired, see below
--   BIO_ASSAY.DESCRIPTION              14   <- repaired here
--   EXPERIMENTAL_DESIGN.DESCRIPTION    13   <- repaired here
--   AUDIT_EVENT.DETAIL / .NOTE          5   <- deliberately NOT repaired, see below
--   BLACKLIST.NAME                      1   <- deliberately NOT repaired, see below
--
-- TREATMENT.DESCRIPTION is the big one and is unsurprising: it holds GEO's growth / treatment /
-- extract / label protocols, which are long prose paragraphs and exactly what gets pasted from Word.
-- All three repaired columns are DERIVED presentational text -- the importer wrote them from the
-- parsed record -- so rewriting them loses nothing that is not recoverable.
--
-- 🛑 INVESTIGATION.SOURCE_METADATA is NOT touched, for two independent reasons.
--   1. It carries a sha256 computed over its own content (with the sha field blanked), so a REPLACE
--      here silently invalidates the hash on all 328 rows and a consumer that re-hashes sees a
--      mismatch it cannot explain. SQL cannot recompute it.
--   2. It is a VERBATIM CACHE of what GEO served. The private-use characters in it are not our
--      corruption -- they are evidence of what the submitter wrote, and that blob is the reference
--      used to recover the true text elsewhere (frinkbro repairs 537 colon-split rows from it).
--      Mangling the reference to tidy the copies is the wrong trade.
--   ⇒ The route for those 328 is to REBUILD the blob through GeoSourceMetadataBuilder, which
--      recomputes the sha and now splits keys correctly. Not a migration.
--
-- 🛑 AUDIT_EVENT.DETAIL / .NOTE are NOT touched: an audit trail records what was said at the time,
-- and editing it to read better is editing history. Left for a human decision.
--
-- 🛑 BLACKLIST.NAME is NOT touched: a blacklist entry may be matched on, and changing a value that
-- participates in matching is a behaviour change wearing a typography fix's clothes.
--
-- All 185 Symbol positions with a non-private-use target, from the same generated table as
-- SymbolFontPua -- not the codepoints a scan happened to observe, which is the mistake V53 made.
-- Idempotent: a second run matches nothing.

