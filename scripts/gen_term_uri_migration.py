#!/usr/bin/env python3
"""Generate scripts/sql/term_uri_migration.sql from the single-source TSV.

    scripts/gen_term_uri_migration.py            # regenerate in place
    scripts/gen_term_uri_migration.py --check    # non-zero if the SQL is stale (for CI)

WHY THIS EXISTS.  The TSV and the SQL held the same rows twice, by hand, and both file headers
claimed the other was generated.  At 20 rows that is survivable; the table is now 97 and a
hand-copy is a drift waiting to happen -- the exact failure the TSV header warns about.

🛑 THE SQL GETS ONLY THE ROWS THAT MIGRATE SOMETHING.  Rows with n_annotations = 0 are in the
table for the RESOLVER, not for the UPDATE: cab's Tier-0 mints CLO_0001199 (22RV1, zero corpus
uses) and asks Gemma which twin to keep, and `GET /annotations/canonicalUris` has to answer.
Putting those rows in the migration would add UPDATEs that match no row -- harmless to run and
actively misleading to read, because the preflight counts would suggest work that does not exist.
"""
from __future__ import annotations

import argparse
import csv
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "gemma-core/src/main/resources/ubic/gemma/core/ontology/TermUriMigration.tsv"
TARGET = ROOT / "scripts/sql/term_uri_migration.sql"

HEADER = """\
-- ---------------------------------------------------------------------------------------
-- Term-URI migration: repoint annotations from a retired URI to the one we keep.
--
-- 🛑 GENERATED by scripts/gen_term_uri_migration.py from
--    gemma-core/src/main/resources/ubic/gemma/core/ontology/TermUriMigration.tsv.
--    Do not edit this file. Edit the TSV and regenerate.
--
-- 🛑 DO NOT RUN THIS YET. It is written, reviewed and parked. Two reasons:
--   1. The Gemma 2.0 write path is HELD -- 2.0 emits 21 audit discriminators Gemma 1.32.7
--      cannot load (PR #1667, open). Anything that audits degrades the 1.0 experiment page.
--   2. 🛑 The agent pipeline runs against a MAY snapshot of Gemma. Migrating prod now puts
--      the corpus out of sync with what the agents were calibrated on. Paul, 2026-08-18:
--      "I don't want to get too out of sync. So we won't actually do the migration now."
--
-- Until it runs, GEMMA RESOLVES THESE AT READ TIME instead -- see
-- CharacteristicUtils#canonicalUri and docs/design/TERM_URI_CANONICALIZATION.md.
--
-- {n_sql} mappings here, {n_ann} annotations. The TSV carries {n_all}; the {n_zero} it holds with
-- n_annotations = 0 are deliberately NOT here. Those exist so the canonicalization endpoint can
-- answer for a twin the corpus has never used -- which is precisely the twin an outside resolver
-- mints and asks about -- and as UPDATEs they would match nothing.
--
--   malformed  -- a URI that is wrong on its face (bare CURIE, colon for underscore, an id
--                 concatenated with itself). Every repair below was verified by resolving
--                 the repaired IRI against the live ontology; none is a guess.
--   clo_twin   -- two live CLO classes for one cell line. Decided mechanically:
--                 R3 an EFO inbound xref (an external ontology's editorial pick),
--                 R4 else whichever carries a definition,
--                 R5 else usage -- safe here ONLY because no member of any group is obsolete,
--                 and only when usage clears an evidence floor (winner >= 2 annotations,
--                 leading by >= 2). A one-annotation margin is one curator's spelling.
--
-- 🛑 AFTER RUNNING: EE2C is a denormalized copy and does NOT follow. Run `updateEe2c`, then
-- resync_ee2c_from_characteristic.sql for the rows the upsert cannot reach, then reindex.
-- ---------------------------------------------------------------------------------------

CREATE TEMPORARY TABLE IF NOT EXISTS TERM_URI_MIGRATION (
  FROM_URI  VARCHAR(255) NOT NULL PRIMARY KEY,
  TO_URI    VARCHAR(255) NOT NULL,
  TO_LABEL  VARCHAR(255) NOT NULL,
  LANE      VARCHAR(16)  NOT NULL
);

INSERT INTO TERM_URI_MIGRATION (FROM_URI, TO_URI, TO_LABEL, LANE) VALUES
"""

BODY = """
-- Step 1 -- PREFLIGHT. Record these counts before applying; they are what step 3 must match.
SELECT m.LANE, COUNT(*) AS n_rows, 'subject' AS slot
  FROM CHARACTERISTIC c JOIN TERM_URI_MIGRATION m ON c.VALUE_URI = m.FROM_URI GROUP BY m.LANE
UNION ALL
SELECT m.LANE, COUNT(*), 'object'
  FROM CHARACTERISTIC c JOIN TERM_URI_MIGRATION m ON c.OBJECT_URI = m.FROM_URI GROUP BY m.LANE
UNION ALL
SELECT m.LANE, COUNT(*), 'second_object'
  FROM CHARACTERISTIC c JOIN TERM_URI_MIGRATION m ON c.SECOND_OBJECT_URI = m.FROM_URI GROUP BY m.LANE;

-- Eyeball 20 before/after pairs.
SELECT c.ID, c.VALUE_URI AS from_uri, c.`VALUE` AS from_label, m.TO_URI, m.TO_LABEL
  FROM CHARACTERISTIC c JOIN TERM_URI_MIGRATION m ON c.VALUE_URI = m.FROM_URI LIMIT 20;

-- Step 2 -- APPLY. Check each row count against step 1 before COMMIT.
START TRANSACTION;

-- The label moves with the URI. Leaving the old label behind is how a row ends up saying
-- one thing and meaning another, and the label is what search and every table render.
UPDATE CHARACTERISTIC c JOIN TERM_URI_MIGRATION m ON c.VALUE_URI = m.FROM_URI
   SET c.VALUE_URI = m.TO_URI, c.`VALUE` = m.TO_LABEL;

UPDATE CHARACTERISTIC c JOIN TERM_URI_MIGRATION m ON c.OBJECT_URI = m.FROM_URI
   SET c.OBJECT_URI = m.TO_URI, c.OBJECT = m.TO_LABEL;

UPDATE CHARACTERISTIC c JOIN TERM_URI_MIGRATION m ON c.SECOND_OBJECT_URI = m.FROM_URI
   SET c.SECOND_OBJECT_URI = m.TO_URI, c.SECOND_OBJECT = m.TO_LABEL;

-- Step 3 -- POSTFLIGHT, inside the transaction so a wrong count can still be rolled back.
-- Must be 0 on every row.
SELECT 'subject remaining (must be 0)' AS chk, COUNT(*) AS n
  FROM CHARACTERISTIC c JOIN TERM_URI_MIGRATION m ON c.VALUE_URI = m.FROM_URI
UNION ALL
SELECT 'object remaining (must be 0)', COUNT(*)
  FROM CHARACTERISTIC c JOIN TERM_URI_MIGRATION m ON c.OBJECT_URI = m.FROM_URI
UNION ALL
SELECT 'second_object remaining (must be 0)', COUNT(*)
  FROM CHARACTERISTIC c JOIN TERM_URI_MIGRATION m ON c.SECOND_OBJECT_URI = m.FROM_URI;

-- COMMIT;    -- uncomment deliberately, after reading step 3
-- ROLLBACK;
"""


def sql_quote(value: str) -> str:
    return "'" + value.replace("\\", "\\\\").replace("'", "''") + "'"


def render() -> str:
    with SOURCE.open(encoding="utf-8") as fh:
        rows = [r for r in csv.DictReader((l for l in fh if not l.startswith("#")), delimiter="\t")]
    migrating = [r for r in rows if int(r["n_annotations"]) > 0]
    head = HEADER.format(n_sql=len(migrating), n_ann=sum(int(r["n_annotations"]) for r in migrating),
                         n_all=len(rows), n_zero=len(rows) - len(migrating))
    values = ",\n".join(
        "  ({}, {}, {}, {})".format(sql_quote(r["from_uri"]), sql_quote(r["to_uri"]),
                                    sql_quote(r["to_label"]), sql_quote(r["lane"]))
        for r in migrating)
    return head + values + ";\n" + BODY


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true",
                    help="exit non-zero if the SQL on disk is not what the TSV would produce")
    args = ap.parse_args()
    rendered = render()
    if args.check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != rendered:
            print(f"STALE: {TARGET} does not match {SOURCE}. Run scripts/gen_term_uri_migration.py.",
                  file=sys.stderr)
            return 1
        print(f"{TARGET.name} is in sync with {SOURCE.name}")
        return 0
    TARGET.write_text(rendered, encoding="utf-8")
    print(f"wrote {TARGET}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
