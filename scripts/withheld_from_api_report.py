#!/usr/bin/env python3
"""Regenerate docs/recce/WITHHELD_FROM_API_TRIAGE.md from the annotations in the source tree.

The source tree is the only input; nothing here is hand-maintained, so re-run this after
every re-reasoning or retirement rather than editing the markdown.

    scripts/withheld_from_api_report.py [--check]

--check exits non-zero if the committed report is stale, for use in review.
"""
import argparse
import re
import subprocess
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs/recce/WITHHELD_FROM_API_TRIAGE.md"

ANNOT = re.compile(r"^\s*@WithheldFromApi\(\s*(?:value\s*=\s*)?Reason\.(\w+)")
COMMENT = re.compile(r'comment\s*=\s*"(.*?)"')
FIELD = re.compile(r"^\s*(?:private|protected|public)\s+.*?\b(\w+)\s*(?:=|;)")
METHOD = re.compile(r"^\s*(?:private|protected|public)\s+.*?\b(\w+)\s*\(")

# UNTRIAGED first: it is the burn-down list and the reason this document exists.
ORDER = ["UNTRIAGED", "CALLER_IDENTITY", "DISCLOSURE", "INTERNAL_ONLY", "REDUNDANT", "POLICY"]

BLURB = {
    "UNTRIAGED": "Real data a client might legitimately want, withheld only because Gemma Web was "
                 "once the consumer and nobody has traced it since. **This is the work list.** "
                 "Retiring one means tracing where it is populated and whether null is meaningful, "
                 "then un-hiding it with a `NON_NULL` guard and a serialization test, then lowering "
                 "`UNTRIAGED_CEILING` in `WithheldFromApiInventoryTest`.",
    "CALLER_IDENTITY": "Depends on who is asking, not on the entity. Never remove one of these "
                       "without replacing it with something stronger.",
    "DISCLOSURE": "Not per-caller, but should not leave the building.",
    "INTERNAL_ONLY": "Cannot mean anything to a client: nothing populates it, its shape is lossy, or "
                     "it sits on a value object nothing serves. Publishing one would be a falsehood, "
                     "so the suppression is enforced. Deleting the member usually beats keeping it.",
    "REDUNDANT": "Already on the wire under another name, or trivially derivable from what is. The "
                 "only bucket asserting *no* hazard, and therefore the only one exempt from the "
                 "suppression enforcement. Safe to delete outright.",
    "POLICY": "Withheld by curation or editorial decision rather than a technical hazard.",
}


def member_name(line):
    eq, par = line.find("="), line.find("(")
    field_first = eq != -1 and (par == -1 or eq < par)
    for rx in ((FIELD, METHOD) if (field_first or par == -1) else (METHOD, FIELD)):
        m = rx.match(line)
        if m:
            return m.group(1), (rx is METHOD)
    return None, False


def scan():
    sites = []
    for path in sorted(ROOT.glob("gemma-*/src/main/java/**/*.java")):
        lines = path.read_text().splitlines()
        if not any(ANNOT.match(l) for l in lines):
            continue
        rel = path.relative_to(ROOT).as_posix()
        for i, line in enumerate(lines):
            m = ANNOT.match(line)
            if not m:
                continue
            note = ""
            for look in lines[i:i + 3]:
                c = COMMENT.search(look)
                if c:
                    note = c.group(1)
                    break
            for j in range(i + 1, min(i + 6, len(lines))):
                s = lines[j].strip()
                if not s or s.startswith(("@", "*", "/", "//")) or s.startswith("comment"):
                    continue
                name, is_method = member_name(lines[j])
                sites.append({"reason": m.group(1), "member": name + ("()" if is_method else ""),
                              "file": rel, "line": j + 1, "note": note})
                break
    return sites


def render(sites):
    by_reason = defaultdict(list)
    for s in sites:
        by_reason[s["reason"]].append(s)
    counts = Counter(s["reason"] for s in sites)
    try:
        sha = subprocess.run(["git", "-C", str(ROOT), "rev-parse", "--short", "HEAD"],
                             capture_output=True, text=True, check=True).stdout.strip()
    except Exception:
        sha = "unknown"

    out = [f"# `@WithheldFromApi` — every suppressed member, by reason", "",
           f"Generated by `scripts/withheld_from_api_report.py` from the source tree at `{sha}`. "
           f"Do not hand-edit; re-run the script.", "",
           f"**{len(sites)} suppressed members** across "
           f"{len({s['file'] for s in sites})} files. The machine-readable pin is "
           f"`gemma-core/src/test/resources/withheld-from-api-inventory.txt`; reason definitions live "
           f"on `WithheldFromApi.Reason`.", "",
           "| reason | members | enforced by the guard? |", "|---|---:|---|"]
    for r in ORDER:
        n = counts.get(r, 0)
        out.append(f"| [`{r}`](#{r.lower().replace('_', '-')}-{n}) | {n} | "
                   f"{'no — asserts no hazard' if r == 'REDUNDANT' else 'yes'} |")
    out.append("")

    for r in ORDER:
        rows = sorted(by_reason.get(r, []), key=lambda s: (s["file"], s["line"]))
        out += ["---", "", f"## {r} ({len(rows)})", "", BLURB[r], ""]
        if not rows:
            out += ["*No members currently carry this reason.*", ""]
            continue
        out += ["| member | file | line | stated reason |", "|---|---|---:|---|"]
        for s in rows:
            out.append(f"| `{s['member']}` | `{s['file']}` | {s['line']} | {s['note'] or '—'} |")
        out.append("")
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if the committed report is stale")
    args = ap.parse_args()
    text = render(scan())
    if args.check:
        current = OUT.read_text() if OUT.exists() else ""
        if current != text:
            print(f"{OUT.relative_to(ROOT)} is stale; re-run scripts/withheld_from_api_report.py",
                  file=sys.stderr)
            return 1
        print(f"{OUT.relative_to(ROOT)} is up to date")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
